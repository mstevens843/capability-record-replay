export interface CodegenResult {
  readonly outDir: string;
  readonly written: readonly string[];
  /** Files whose content already matched. `pnpm codegen --check` reports drift from this. */
  readonly unchanged: readonly string[];
}

/**
 * Write the generated modules.
 *
 * Rewriting a file whose bytes already match is avoided on purpose: a codegen step that touches
 * every file on every run makes `git status` useless and makes a build cache miss on nothing.
 */
export function writeGenerated(
  contracts: readonly CapabilityContract[],
  outDir: string,
): CodegenResult {
  mkdirSync(outDir, { recursive: true });
  const modules = [...contracts.map(generateContractModule), generateIndexModule(contracts)];
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const module of modules) {
    const path = join(outDir, module.path);
    if (sameContent(path, module.source)) {
      unchanged.push(module.path);
      continue;
    }
    writeFileSync(path, module.source);
    written.push(module.path);
  }
  return { outDir, written, unchanged };
}

function sameContent(path: string, source: string): boolean {
  try {
    return readFileSync(path, "utf8") === source;
  } catch {
    return false;
  }
}
