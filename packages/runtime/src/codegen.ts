// `pnpm codegen` - the contract, as types a caller's compiler can hold to.
//
// WHAT THIS BUYS, precisely. `ReplayOutcomeArm<C>` distributes over `C["outcomes"]`, so when `C` is
// a LITERAL type the caller's `switch (r.outcome)` is exhaustive and adding an `OutcomeDecl` to the
// contract is a compile error at every existing call site. That is correct: a new possible answer
// IS a breaking change for a caller. But it only holds while `C` is literal. Hand a caller
// `CapabilityContract` - whose `outcomes` is `readonly OutcomeDecl[]` - and `O["code"]` widens to
// `string`, the switch silently decays into a string comparison, and the mechanism is gone with no
// diagnostic anywhere. So the generated file exists to keep `C` literal, and the runtime digest pin
// exists because a generated file can also be STALE, which no amount of literal typing detects.
//
// WHY A `.ts` AND NOT A `.d.ts`, which is what SPEC section 2.6 says. A `.d.ts` cannot carry a
// runtime value, and `Invocation.capability.contractDigest` is a runtime value: the pin has to
// travel on the wire to be compared against the contract the host loaded. Emitting a declaration
// file would give the caller literal types and then leave it to hand-copy the digest beside them -
// which is precisely the drift the pin exists to catch, reintroduced one layer down. So the emitted
// module is a `.ts` exporting the contract `as const` plus `CONTRACT_DIGEST`, and `tsc` produces the
// `.d.ts` from it. The caller gets both halves and neither can be stale without the other.
//
// THE OUTPUT IS DETERMINISTIC. Same contract in, byte-identical file out, because the file is
// checked in and a codegen step that reorders keys makes every regeneration a diff nobody reads.
// Key order follows the contract schema's own declaration order rather than the input document's,
// so a re-serialised contract cannot change the emitted bytes either.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CapabilityContract, OutcomeDecl } from "@crr/core";

/** What one contract compiles to. `path` is relative to the output directory. */
export interface GeneratedModule {
  readonly path: string;
  readonly source: string;
}

const BANNER = [
  "// GENERATED BY `pnpm codegen`. DO NOT EDIT.",
  "//",
  "// Regenerate after any contract change. The `CONTRACT_DIGEST` below travels on every invocation",
  "// and is compared against the contract the host loaded: if this file is stale the run comes back",
  "// `failed / contract-stale` before a session is brokered, rather than handing this caller an",
  "// outcome its `switch` has never heard of.",
  "",
  "",
].join("\n");

/** `corebank.member.read_share_position` -> `corebank-member-read_share_position.ts` is ugly; the
 *  dots become path-safe underscores and the file keeps the capability's own spelling otherwise. */
export function moduleFileNameOf(capabilityName: string): string {
  return `${capabilityName.replace(/\./g, "__")}.ts`;
}

/** `corebank.member.read_share_position` -> `corebankMemberReadSharePosition`. */
export function identifierOf(capabilityName: string): string {
  const parts = capabilityName.split(/[._-]/).filter((p) => p.length > 0);
  const [head, ...tail] = parts;
  if (head === undefined) throw new Error(`${capabilityName} has no identifier form`);
  return head + tail.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
}

function pascalOf(capabilityName: string): string {
  const id = identifierOf(capabilityName);
  return id.charAt(0).toUpperCase() + id.slice(1);
}

