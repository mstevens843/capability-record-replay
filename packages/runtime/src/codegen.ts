// The emitter
// ---------------------------------------------------------------------------------------------

/**
 * One contract, as a TypeScript module.
 *
 * The contract is emitted as a literal with three assertion sites - `name`, `version`, `digest` -
 * because those three are BRANDED types in `@crr/core` and a bare string literal does not inhabit a
 * brand. Everything else is emitted as a plain literal so `as const` gives it a literal type, which
 * is the entire point: `outcomes[n].code` must be `"MEMBER_NOT_FOUND"` and not `string`.
 *
 * `satisfies CapabilityContract` is the assertion that the emitted literal is a real contract. It
 * checks assignability WITHOUT widening the literal, which `: CapabilityContract` would do - and a
 * widened annotation here would silently undo the whole mechanism while still compiling.
 */
export function generateContractModule(contract: CapabilityContract): GeneratedModule {
  const id = identifierOf(contract.name);
  const Pascal = pascalOf(contract.name);
  const body = literal(contract, 0);

  const source = `${BANNER}import type {
  ArgsOf,
  CapabilityContract,
  CapabilityName,
  ContractVersion,
  Digest,
  Invocation,
  OutputsOf,
  ReplayResult,
  WithApproval,
} from "@crr/core";

export const ${id} = ${body} as const satisfies CapabilityContract;

export type ${Pascal} = typeof ${id};

/** The pin. Travels on every invocation; a mismatch is \`failed / contract-stale\`. */
export const CONTRACT_DIGEST = ${JSON.stringify(contract.digest)} as Digest;

/** Spread into an \`Invocation\` so the three identity fields cannot be typed by hand. */
export const CAPABILITY = {
  name: ${JSON.stringify(contract.name)} as CapabilityName,
  version: ${JSON.stringify(contract.version)} as ContractVersion,
  contractDigest: CONTRACT_DIGEST,
} as const;

export type ${Pascal}Args = ArgsOf<${Pascal}>;
export type ${Pascal}Outputs = OutputsOf<${Pascal}>;
/** Four arms. \`switch (r.status)\`, then \`switch (r.outcome)\` - both exhaustive. */
export type ${Pascal}Result = ReplayResult<${Pascal}>;
export type ${Pascal}Invocation = Invocation<${Pascal}>;
/** The approval token is required BY THE TYPE when the capability is irreversible. */
export type ${Pascal}Call = WithApproval<${Pascal}>;

/** Every declared business outcome. An outcome is an ANSWER, not an error. */
export type ${Pascal}Outcome = ${outcomeUnion(contract.outcomes)};
`;

  return { path: moduleFileNameOf(contract.name), source };
}

function outcomeUnion(outcomes: readonly OutcomeDecl[]): string {
  if (outcomes.length === 0) return "never";
  return outcomes.map((o) => JSON.stringify(o.code)).join(" | ");
}

/**
 * A value as TypeScript source.
 *
 * Object keys are emitted in the order the source document holds them, which for a document that
 * came through `parseContract` is the schema's declaration order rather than whatever the JSON file
 * happened to use - zod's `strictObject` rebuilds the object key by key. That is what makes the
 * output deterministic across a re-serialised input.
 */
function literal(value: unknown, depth: number, key?: string): string {
  const pad = "  ".repeat(depth + 1);
  const closePad = "  ".repeat(depth);

  if (value === null) return "null";
  if (typeof value === "string") {
    const text = JSON.stringify(value);
    // Depth 1 is a TOP-LEVEL property of the contract, and only there. A `name` inside a
    // `FieldSpec` or a table column is a plain string; branding one would not compile, and a
    // brand table keyed by name alone would try.
    //
    // The assertion is to the INTERSECTION of the brand and the literal, not to the brand alone.
    // `"mock.member.find" as CapabilityName` type-checks and quietly widens the property to
    // `CapabilityName`, which throws away the literal this whole file exists to preserve -
    // `Invocation<C>["capability"]["name"]` is `C["name"]`, and a caller should not be able to
    // invoke one capability with another's identity because the type said `string`.
    const brand = depth === 1 && key !== undefined ? BRANDS[key] : undefined;
    return brand === undefined ? text : `${text} as ${brand} & ${text}`;
  }
  if (typeof value === "number" || typeof value === "boolean") return String(value);

  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const items = value.map((item) => `${pad}${literal(item, depth + 1)}`);
    return `[\n${items.join(",\n")},\n${closePad}]`;
  }

  const entries = Object.entries(value as Record<string, unknown>).filter(
    ([, v]) => v !== undefined,
  );
  if (entries.length === 0) return "{}";
  const lines = entries.map(([k, v]) => `${pad}${propertyKey(k)}: ${literal(v, depth + 1, k)}`);
  return `{\n${lines.join(",\n")},\n${closePad}}`;
}

/** The three branded string fields on a contract. */
const BRANDS: Readonly<Record<string, string>> = {
  name: "CapabilityName",
  version: "ContractVersion",
  digest: "Digest",
};

function propertyKey(key: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

