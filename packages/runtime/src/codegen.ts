// The barrel
// ---------------------------------------------------------------------------------------------

/** One import site for a caller that holds several capabilities. */
export function generateIndexModule(contracts: readonly CapabilityContract[]): GeneratedModule {
  const lines = [BANNER];
  for (const contract of [...contracts].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(
      `export * as ${identifierOf(contract.name)} from "./${moduleFileNameOf(contract.name).replace(/\.ts$/, ".js")}";`,
    );
  }
  return { path: "index.ts", source: `${lines.join("\n")}\n` };
}

