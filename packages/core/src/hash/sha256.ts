// A vendored, synchronous SHA-256 (FIPS 180-4), plus the UTF-8 encoder it is fed from.
//
// WHY this is not `crypto.subtle.digest` and not the platform hash module:
//
//   1. `@crr/core` is pure by contract, and a source-scanning test fails the build if a platform
//      module import appears anywhere in this directory. That contract is the architectural claim
//      of the whole project - the linker, the classifier and the digest are functions of their
//      arguments and nothing else - so the hash has to live inside the purity boundary, not punch
//      a hole through it.
//   2. `crypto.subtle.digest` is async. Making it the hash would make `digestOf` async, which
//      would make the linker async, which would make every one of the 28 link checks a promise.
//      A content address is a property of a document, not an I/O operation.
//   3. The digest is what an approval signature is taken over. It has to be computed identically
//      by the recorder, the linker, the replayer and a reviewer's script, on whatever runtime each
//      happens to be. One vendored implementation with published test vectors is a shorter path to
//      that than four platform APIs that agree until they do not.
//
// The cost is ~110 lines of well-understood code, pinned in test/sha256.test.ts to the published
// FIPS 180-4 vectors plus boundary vectors generated by an independent implementation.
//
// This is not a general-purpose crypto library. It hashes short canonical documents. It is not
// constant-time and must not be used for anything where that matters.

